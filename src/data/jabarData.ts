// PREDICTIVE ENGINE: Predict future performance based on traffic projection, demographic growth, industry fit, and seasonality
import { PredictiveScenario, PredictiveSpotResult, ReportConfig } from '../types/ooh';

export function runPredictiveLocationAnalysis(
  spots: BillboardSpot[],
  scenario: PredictiveScenario
): PredictiveSpotResult[] {
  return spots.map(spot => {
    // 1. Industry affinity score
    let industryAffinity = 1.0;
    const t = spot.type.toLowerCase();
    const r = spot.roadType.toLowerCase();
    const reg = spot.regency.toLowerCase();

    if (scenario.targetIndustry === 'Otomotif & Transportasi') {
      if (r.includes('tol') || spot.name.includes('Pasteur') || spot.name.includes('Ahmad Yani')) industryAffinity = 1.35;
      else if (t.includes('videotron')) industryAffinity = 1.15;
    } else if (scenario.targetIndustry === 'FMCG & F&B') {
      if (r.includes('komersial') || spot.name.includes('Dago') || spot.name.includes('Margonda') || spot.name.includes('Mustofa')) industryAffinity = 1.30;
      else if (spot.avgDwellTimeSec > 45) industryAffinity = 1.22;
    } else if (scenario.targetIndustry === 'Perbankan & Fintech') {
      if (spot.name.includes('Asia Afrika') || spot.name.includes('Summarecon') || spot.name.includes('Kujang')) industryAffinity = 1.32;
      else industryAffinity = 1.10;
    } else if (scenario.targetIndustry === 'E-Commerce & Digital Tech') {
      if (t.includes('videotron') || spot.name.includes('Paskal') || spot.name.includes('Juanda')) industryAffinity = 1.28;
    } else if (scenario.targetIndustry === 'Properti & Residensial') {
      if (reg.includes('bekasi') || reg.includes('karawang') || reg.includes('bogor')) industryAffinity = 1.26;
    }

    // 2. Seasonality multiplier
    let seasonMultiplier = 1.0;
    if (scenario.seasonality === 'Mudik & Libur Lebaran') {
      if (r.includes('tol') || spot.name.includes('Pasteur') || reg.includes('cirebon')) seasonMultiplier = 1.45;
      else seasonMultiplier = 0.95; // city center office drop
    } else if (scenario.seasonality === 'Liburan Sekolah / Akhir Tahun') {
      if (reg.includes('bandung') || reg.includes('bogor')) seasonMultiplier = 1.30;
      else seasonMultiplier = 1.10;
    } else if (scenario.seasonality === 'Festival Belanja Q4') {
      if (r.includes('komersial')) seasonMultiplier = 1.24;
      else seasonMultiplier = 1.12;
    }

    // 3. Infrastructure & Demographic Growth Multiplier
    const regencyMeta = WEST_JAVA_REGENCIES.find(regItem => regItem.name === spot.regency);
    const regencyGrowthRate = (regencyMeta?.projectedAnnualGrowthPct || 5.0) / 100;
    const baseTrafficGrowth = 1 + (scenario.trafficGrowthRatePct / 100);

    let infraMultiplier = 1.0;
    if (scenario.infrastructureImpact === 'Aktivasi Tol Baru / LRT') {
      if (spot.regency.includes('Sumedang') || spot.regency.includes('Bekasi') || spot.regency.includes('Bandung')) {
        infraMultiplier = 1.18;
      }
    } else if (scenario.infrastructureImpact === 'Perluasan Pusat Niaga') {
      if (r.includes('komersial')) infraMultiplier = 1.15;
    }

    // Compound Growth
    const compoundGrowth = industryAffinity * seasonMultiplier * (1 + regencyGrowthRate * 0.7) * (baseTrafficGrowth) * infraMultiplier;
    const projectedReach = Math.round(spot.dailyGrossReach * compoundGrowth);
    const projectedVac = Math.round(spot.vacDaily * compoundGrowth);
    
    // Predicted effectiveness score
    const predictedEffectiveness = Math.round(Math.min(99, spot.effectivenessScore * (0.85 + (compoundGrowth * 0.15))));
    const growthDeltaPct = Math.round(((projectedVac - spot.vacDaily) / spot.vacDaily) * 100);

    // Projected ROI Multiplier
    const projectedRoiScore = parseFloat((((projectedVac / spot.vacDaily) * (industryAffinity))).toFixed(2));

    // Confidence Level based on historical data consistency
    const confidenceScore = Math.round(85 + (spot.visibilityScore * 0.1) + (spot.effectivenessScore * 0.04));

    // Strategic Rationale narrative
    let strategicRationale = '';
    if (compoundGrowth > 1.30) {
      strategicRationale = `Titik ini diproyeksikan mengalami lonjakan audiens signifikan (+${growthDeltaPct}%) berkat keselarasan tinggi antara industri ${scenario.targetIndustry} dengan tren musiman ${scenario.seasonality} dan koridor ${spot.roadType}.`;
    } else if (compoundGrowth > 1.15) {
      strategicRationale = `Pertumbuhan stabil positif dipicu oleh arus komuter harian yang konsisten dan tingkat keterlihatan (VAC) yang solid di area ${spot.regency}.`;
    } else {
      strategicRationale = `Kinerja stabil dengan risiko fluktuasi rendah. Sangat cocok untuk kampanye berorientasi brand sustenance jangka panjang.`;
    }

    let recommendedCategory: 'Top Priority Future Placement' | 'High Growth Transit' | 'Stable Sustained Performer' = 'Stable Sustained Performer';
    if (predictedEffectiveness >= 94 || growthDeltaPct >= 28) {
      recommendedCategory = 'Top Priority Future Placement';
    } else if (spot.roadType.includes('Tol') || growthDeltaPct >= 18) {
      recommendedCategory = 'High Growth Transit';
    }

    return {
      spot,
      currentEffectiveness: spot.effectivenessScore,
      predictedEffectiveness,
      projectedVac,
      projectedReach,
      projectedRoiScore,
      growthDeltaPct,
      confidenceScore: Math.min(98, confidenceScore),
      strategicRationale,
      recommendedCategory
    };
  }).sort((a, b) => b.predictedEffectiveness - a.predictedEffectiveness);
}

// AUTOMATED REPORT GENERATOR: Aggregates metrics for daily/weekly/monthly/quarterly
export function compilePerformanceReport(
  spots: BillboardSpot[],
  config: ReportConfig
) {
  const selectedList = spots.filter(s => config.selectedSpots.includes(s.id));
  const activeSpots = selectedList.length > 0 ? selectedList : spots;

  const multiplier = 
    config.timeRange === 'daily' ? 1 :
    config.timeRange === 'weekly' ? 7 :
    config.timeRange === 'monthly' ? 30 : 90;

  const periodLabel = 
    config.timeRange === 'daily' ? 'Harian (24 Jam)' :
    config.timeRange === 'weekly' ? 'Mingguan (7 Hari)' :
    config.timeRange === 'monthly' ? 'Bulanan (30 Hari)' : 'Triwulan (90 Hari)';

  const totalGrossReach = activeSpots.reduce((acc, s) => acc + (s.dailyGrossReach * multiplier), 0);
  const totalVac = activeSpots.reduce((acc, s) => acc + (s.vacDaily * multiplier), 0);
  const avgDwell = Math.round(activeSpots.reduce((acc, s) => acc + s.avgDwellTimeSec, 0) / activeSpots.length);
  const avgFrequency = parseFloat((activeSpots.reduce((acc, s) => acc + (s.avgFrequency || 3.2), 0) / activeSpots.length).toFixed(1));
  const netUniqueReach = Math.round(totalGrossReach / (avgFrequency || 1));
  const avgEffectiveness = Math.round(activeSpots.reduce((acc, s) => acc + s.effectivenessScore, 0) / activeSpots.length);
  const totalCost = activeSpots.reduce((acc, s) => acc + ((s.ratePerMonthIdr / 30) * multiplier), 0);
  const blendedCpm = totalVac > 0 ? Math.round((totalCost / totalVac) * 1000) : 0;

  // Regional breakdown
  const regencyMap: { [key: string]: { reach: number; vac: number; spotCount: number } } = {};
  activeSpots.forEach(s => {
    if (!regencyMap[s.regency]) {
      regencyMap[s.regency] = { reach: 0, vac: 0, spotCount: 0 };
    }
    regencyMap[s.regency].reach += s.dailyGrossReach * multiplier;
    regencyMap[s.regency].vac += s.vacDaily * multiplier;
    regencyMap[s.regency].spotCount += 1;
  });

  const regionalBreakdown = Object.keys(regencyMap).map(reg => ({
    regency: reg,
    reach: regencyMap[reg].reach,
    vac: regencyMap[reg].vac,
    spotCount: regencyMap[reg].spotCount,
    sharePct: parseFloat(((regencyMap[reg].vac / (totalVac || 1)) * 100).toFixed(1))
  })).sort((a, b) => b.vac - a.vac);

  return {
    meta: {
      campaignName: config.campaignName || 'Kampanye Multi-Spot Jawa Barat',
      brandClient: config.brandClient || 'Klien Korporat',
      timeRange: config.timeRange,
      periodLabel,
      generatedAt: new Date().toLocaleDateString('id-ID', { year: 'numeric', month: 'long', day: 'numeric', hour: '2-digit', minute: '2-digit' }),
      totalSpotsCount: activeSpots.length,
      notes: config.notes
    },
    metrics: {
      totalGrossReach,
      netUniqueReach,
      totalVac,
      avgFrequency,
      avgDwell,
      avgEffectiveness,
      totalCost,
      blendedCpm
    },
    spotsDetail: activeSpots.map(s => ({
      code: s.code,
      name: s.name,
      regency: s.regency,
      roadName: s.roadName,
      type: s.type,
      reach: s.dailyGrossReach * multiplier,
      vac: s.vacDaily * multiplier,
      frequency: s.avgFrequency || 3.2,
      dwell: s.avgDwellTimeSec,
      effectiveness: s.effectivenessScore,
      cost: Math.round((s.ratePerMonthIdr / 30) * multiplier),
      cpm: s.cpmIdr
    })),
    regionalBreakdown
  };
}

