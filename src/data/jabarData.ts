// Location Effectiveness Formula:
// Evaluates placement effectiveness on a 0-100 index based on:
// 1. Traffic Volume (Gross Reach) - 30% weight
// 2. Viewing Dwell Time (Traffic slowing/stopping effect) - 25% weight
// 3. Line-of-sight & Angle unobstructed (Visibility Score) - 20% weight
// 4. Clutter Absence (Low clutter gets bonus, crowded loses score) - 15% weight
// 5. Commercial corridor purchasing power - 10% weight
export function calculateLocationEffectiveness(
  reach: number,
  dwellTimeSec: number,
  visibilityScore: number,
  clutter: 'Rendah (Unobstructed)' | 'Sedang (Normal)' | 'Tinggi (Kompetitif)',
  roadType: string
): number {
  const reachScore = Math.min(100, (reach / 300000) * 100);
  const dwellScore = Math.min(100, (dwellTimeSec / 60) * 100);
  const visScore = Math.min(100, visibilityScore);
  const clutterScore = clutter === 'Rendah (Unobstructed)' ? 100 : clutter === 'Sedang (Normal)' ? 80 : 60;
  
  const roadScore = 
    roadType.includes('Kawasan Komersial') ? 95 :
    roadType.includes('Jalan Tol') ? 90 :
    roadType.includes('Arteri Primer') ? 88 : 75;

  const total = (
    reachScore * 0.30 +
    dwellScore * 0.25 +
    visScore * 0.20 +
    clutterScore * 0.15 +
    roadScore * 0.10
  );

  return Math.round(Math.min(99, Math.max(40, total)));
}

// Generate 12-Month Historical Performance Trend for a billboard
export function generateSpotHistoricalTrend(spot: BillboardSpot) {
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'Mei', 'Jun', 'Jul', 'Agu', 'Sep', 'Okt', 'Nov', 'Des'];
  const baseReach = spot.dailyGrossReach;
  const isHighway = spot.roadType.includes('Tol');
  const isBandungOrPuncak = spot.regency.includes('Bandung') || spot.regency.includes('Bogor');

  return months.map((month, idx) => {
    // Seasonality factors:
    // Apr/Mei (Lebaran Mudik) -> Tol Japek, Cipali, Pasteur +35% to +45%
    // Jun/Jul (Libur Sekolah) -> Bandung & Bogor +20%
    // Des (Akhir Tahun) -> +25%
    // Feb/Agu (Reguler) -> 0%
    let seasonalMult = 1.0;
    if (idx === 3 || idx === 4) { // Apr - Mei
      seasonalMult = isHighway ? 1.42 : 1.15;
    } else if (idx === 5 || idx === 6) { // Jun - Jul
      seasonalMult = isBandungOrPuncak ? 1.25 : 1.08;
    } else if (idx === 11) { // Des
      seasonalMult = 1.28;
    } else if (idx === 1) { // Feb
      seasonalMult = 0.94;
    }

    const reach = Math.round(baseReach * seasonalMult);
    const vac = Math.round(reach * (spot.vacDaily / spot.dailyGrossReach));
    const trafficIndex = Math.round(seasonalMult * 100);
    const occupancyPercent = idx === 3 || idx === 11 ? 100 : idx % 3 === 0 ? 92 : 85;

    return {
      month: `${month} 2025/2026`,
      year: 2026,
      grossReach: reach,
      vac,
      trafficIndex,
      occupancyPercent
    };
  });
}

